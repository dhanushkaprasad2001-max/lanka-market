-- LankaMarket Supabase database setup
-- Run this entire file once in Supabase Dashboard > SQL Editor > New query.
-- Safe to re-run for the tables, policies and seed rows defined here.

create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text,
  phone text,
  district text,
  role text not null default 'user' check (role in ('user','admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  name text not null,
  slug text not null unique,
  icon text not null default '🛍️',
  parent_id bigint references public.categories(id) on delete restrict,
  is_active boolean not null default true,
  sort_order integer not null default 0,
  unique (parent_id, name)
);

create table if not exists public.districts (
  id bigint generated by default as identity primary key,
  name text not null unique,
  province text not null
);

create table if not exists public.listings (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  category_id bigint not null references public.categories(id),
  district_id bigint not null references public.districts(id),
  title text not null check (char_length(title) between 5 and 100),
  description text not null check (char_length(description) between 10 and 5000),
  price numeric(14,2) not null default 0 check (price >= 0),
  negotiable boolean not null default false,
  item_condition text not null default 'Not specified'
    check (item_condition in ('New','Used','Not specified')),
  contact_phone text not null,
  whatsapp_phone text,
  status text not null default 'pending'
    check (status in ('pending','approved','rejected','sold','expired')),
  views_count integer not null default 0 check (views_count >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  expires_at timestamptz not null default (now() + interval '60 days')
);

create table if not exists public.listing_images (
  id uuid primary key default gen_random_uuid(),
  listing_id uuid not null references public.listings(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  image_path text not null,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  unique (listing_id, image_path)
);

create table if not exists public.favorites (
  user_id uuid not null references auth.users(id) on delete cascade,
  listing_id uuid not null references public.listings(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, listing_id)
);

create table if not exists public.listing_reports (
  id uuid primary key default gen_random_uuid(),
  listing_id uuid not null references public.listings(id) on delete cascade,
  reporter_id uuid references auth.users(id) on delete set null,
  reason text not null check (char_length(reason) between 5 and 1000),
  status text not null default 'open' check (status in ('open','reviewing','resolved','dismissed')),
  created_at timestamptz not null default now()
);

create index if not exists listings_browse_idx
  on public.listings (status, category_id, district_id, created_at desc);
create index if not exists listings_user_idx on public.listings (user_id, created_at desc);
create index if not exists listing_images_listing_idx on public.listing_images (listing_id, sort_order);
create index if not exists favorites_user_idx on public.favorites (user_id);

create or replace function public.is_lankamarket_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid() and role = 'admin'
  );
$$;

create or replace function public.create_lankamarket_profile()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, full_name)
  values (new.id, coalesce(new.raw_user_meta_data->>'full_name', ''))
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created_lankamarket on auth.users;
create trigger on_auth_user_created_lankamarket
after insert on auth.users
for each row execute procedure public.create_lankamarket_profile();

create or replace function public.guard_lankamarket_profile_role()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if auth.uid() is not null and new.role is distinct from old.role
     and not public.is_lankamarket_admin() then
    raise exception 'You cannot change your account role';
  end if;
  return new;
end;
$$;

drop trigger if exists guard_lankamarket_profile_role_trigger on public.profiles;
create trigger guard_lankamarket_profile_role_trigger
before update on public.profiles
for each row execute procedure public.guard_lankamarket_profile_role();

create or replace function public.guard_lankamarket_listing_status()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if tg_op = 'INSERT' then
    if not public.is_lankamarket_admin() then
      new.status := 'pending';
    end if;
  elsif auth.uid() is not null and not public.is_lankamarket_admin() then
    if new.user_id is distinct from old.user_id then
      raise exception 'Listing owner cannot be changed';
    end if;
    if new.status is distinct from old.status
       and not (old.status = 'approved' and new.status = 'sold') then
      raise exception 'Only an administrator can change listing approval status';
    end if;
  end if;
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists guard_lankamarket_listing_status_trigger on public.listings;
create trigger guard_lankamarket_listing_status_trigger
before insert or update on public.listings
for each row execute procedure public.guard_lankamarket_listing_status();

